export function Icon({
  name,
  className,
  fallback = "Layers",
}: {
  name?: string | null;
  className?: string;
  fallback?: string;
}) {
  if (!name) return null;
  if (isBrandIcon(name)) {
    return <BrandIcon name={name} className={cn("h-5 w-5", className)} />;
  }
  const Component = icons[name] ?? icons[fallback] ?? Layers;
  return <Component className={cn("h-5 w-5", className)} aria-hidden />;
}
